/** Returns the static surname bank for a race, or undefined for an unknown id. */
export function getPlayerSurnameBank(raceId: string): string[] | undefined {
  return PLAYER_SURNAME_BANKS[raceId];
}

/**
 * Composes a random `"{first} {surname}"` player name for `raceId`:
 * a random unused first name combined with a random surname whose
 * `"first surname"` pair is not already in `usedNames`. When the surname bank
 * is absent or every remaining combination is used, falls back to a bare first
 * name; when the first-name bank is exhausted or the race is unknown, falls
 * back to `${fallbackPrefix ?? "Player"} ${usedNames.size + 1}`.
 */
export function randomPlayerName(
  raceId: string,
  usedNames?: Set<string>,
  fallbackPrefix?: string,
  /** Optional deterministic source of floats in [0, 1) — defaults to
   * `Math.random`. Passed by the journeyman naming path so the same team's
   * journeyman gets the SAME name on every serve (RAU-13 determinism). */
  rng: () => number = Math.random,
): string {
  const used = usedNames ?? new Set<string>();
  const firstBank = getPlayerNameBank(raceId);
  if (!firstBank || firstBank.length === 0) {
    return `${fallbackPrefix ?? "Player"} ${used.size + 1}`;
  }

  const surnameBank = getPlayerSurnameBank(raceId);
  const availableFirsts = firstBank.filter((first) => !used.has(first));

  if (surnameBank && surnameBank.length > 0) {
    // Every unused "First Surname" combination, so the same pair is never
    // re-used across one roster.
    const fullNames: string[] = [];
    for (const first of availableFirsts) {
      for (const surname of surnameBank) {
        const full = `${first} ${surname}`;
        if (!used.has(full)) fullNames.push(full);
      }
    }
    if (fullNames.length > 0) {
      return fullNames[Math.floor(rng() * fullNames.length)];
    }
  }

  // Surname bank absent or exhausted: fall back to a bare first name.
  if (availableFirsts.length > 0) {
    return availableFirsts[Math.floor(rng() * availableFirsts.length)];
  }

  return `${fallbackPrefix ?? "Player"} ${used.size + 1}`;
}
