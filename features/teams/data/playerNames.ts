/** Returns the static name bank for a race, or undefined for an unknown id. */
export function getPlayerNameBank(raceId: string): string[] | undefined {
  return PLAYER_NAME_BANKS[raceId];
}

/**
 * Picks a random bank name for `raceId` that is not in `usedNames`. When the
 * bank is exhausted or the race is unknown, falls back to
 * `${fallbackPrefix ?? "Player"} ${usedNames.size + 1}`.
 */
export function randomPlayerName(
  raceId: string,
  usedNames?: Set<string>,
  fallbackPrefix?: string,
): string {
  const used = usedNames ?? new Set<string>();
  const bank = getPlayerNameBank(raceId);
  const available = bank?.filter((name) => !used.has(name)) ?? [];
  if (available.length === 0) {
    return `${fallbackPrefix ?? "Player"} ${used.size + 1}`;
  }
  return available[Math.floor(Math.random() * available.length)];
}
