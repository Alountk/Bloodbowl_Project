/** Returns the static team-name bank for a race, or undefined for an unknown id. */
export function getTeamNameBank(raceId: string): string[] | undefined {
  return TEAM_NAME_BANKS[raceId];
}

/**
 * Picks a random team name for `raceId` that is not in `usedNames`. When the
 * bank is absent or exhausted, returns `""` so the caller keeps showing the
 * empty name field.
 */
export function randomTeamName(raceId: string, usedNames?: Set<string>): string {
  const used = usedNames ?? new Set<string>();
  const bank = getTeamNameBank(raceId);
  const available = bank?.filter((name) => !used.has(name)) ?? [];
  if (available.length === 0) return "";
  return available[Math.floor(Math.random() * available.length)];
}
